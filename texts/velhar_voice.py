# ─── Динамический текст ожидания ──────────────────────────────────────────────

LOADING_WORDS = ["эхо", "узор", "тишина", "след", "волна", "отражение"]


def get_loading(spread_type: str, moon_phase: str, time_of_day: str) -> str:
    word = random.choice(LOADING_WORDS)
    templates = {
        "spread_day": (
            f"Велхар погружается в {word} текущего дня...\n"
            f"Одна карта. Одно послание. Именно для тебя. 🌌"
        ),
        "spread_question": (
            f"Велхар раскидывает карты в пространстве...\n"
            f"{moon_phase.capitalize()}. {word.capitalize()} разворачивается. 🔮"
        ),
        "spread_deep": (
            f"Велхар открывает глубокий канал...\n"
            f"Пять карт выстраиваются в узор.\n"
            f"Такие вещи не терпят спешки. ✨"
        ),
        "spread_year": (
            f"Велхар разворачивает временной поток...\n"
            f"Двенадцать карт. Двенадцать месяцев.\n"
            f"{time_of_day.capitalize()} — хорошее время для таких вопросов. 🌙"
        ),
        "spread_compat": (
            f"Велхар видит двух людей в пространстве...\n"
            f"Нити между вами уже существуют.\n"
            f"Карты лишь сделают их видимыми. ✨"
        ),
        "ritual": (
            f"Велхар открывает лунное пространство...\n"
            f"{moon_phase.capitalize()} усиливает восприятие.\n"
            f"Готовься увидеть. 🌕"
        ),
        "month_spread": (
            f"Велхар читает поток предстоящего месяца...\n"
            f"{word.capitalize()} и свет — для тебя. 🌙"
        ),
    }
    return templates.get(spread_type, f"Велхар погружается в {word}... 🌌")
